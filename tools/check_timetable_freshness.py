#!/usr/bin/env python3
"""Fail if the compiled timetable's validity window is closing.

FINDING F-1 (2026-08 adversarial review): the compiled schedule in
src/timetable_data.h expires -- serviceForDate() falls back to plain
weekday/weekend once a date runs past kTimetableLastOverride, which is wrong
on the next unlisted holiday. A README line saying "regenerate this" is not a
control; this is. It fails while there is still time to act (a 90-day
window), not on the day the data actually goes stale.

Run by two workflows, deliberately with different consequences:

  * .github/workflows/ci.yml       on every push/PR -- a VISIBLE red check,
                                   but NOT a required one (see below).
  * .github/workflows/timetable-watch.yml  weekly -- opens a tracking issue
                                   so the warning reaches someone even when
                                   nobody is opening PRs.

Why it is not a required merge gate: whether it passes depends on Caltrain
publishing a newer GTFS feed, not on anything in the PR under test. In
2026-11 the newest published feed still ended 2027-01-31, so this check was
unfixably red and blocked every merge -- security bumps included -- for
months. A gate nobody can turn green only trains people to bypass gates.

    python3 tools/check_timetable_freshness.py            # exit 1 if closing
    python3 tools/check_timetable_freshness.py --days 30  # a different window

Exit codes: 0 fresh, 1 window closing (or already past), 2 header unreadable.
"""

import argparse
import datetime
import pathlib
import re
import sys

HEADER_PATH = pathlib.Path(__file__).resolve().parent.parent / "src" / "timetable_data.h"

# Matches the 90-day rationale in the F-1 write-up: long enough that a
# failure gives a real chance to notice, fetch a new GTFS feed, and merge
# before the data is actually wrong on the desk.
WARNING_DAYS = 90


def extract(header: str, name: str) -> int | None:
    """Pull a `inline constexpr uint32_t NAME = YYYYMMDD;` value out of the header."""
    m = re.search(rf"inline constexpr uint32_t {name} = (\d+);", header)
    return int(m.group(1)) if m else None


def to_date(yyyymmdd: int) -> datetime.date:
    s = str(yyyymmdd)
    return datetime.date(int(s[0:4]), int(s[4:6]), int(s[6:8]))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--header", default=str(HEADER_PATH))
    parser.add_argument("--days", type=int, default=WARNING_DAYS,
                        help=f"warning window in days (default {WARNING_DAYS})")
    args = parser.parse_args()

    header = pathlib.Path(args.header).read_text()

    # Two different dates, and the EARLIER one is what actually bounds
    # correctness: kTimetableLastOverride (the last known holiday pattern)
    # usually runs out before kTimetableFeedEnd (the GTFS feed's own declared
    # validity end). See timetableExpired() in src/timetable.h.
    values = {}
    for name in ("kTimetableLastOverride", "kTimetableFeedEnd"):
        values[name] = extract(header, name)
        if values[name] is None:
            print(f"::error::{name} not found in {args.header} -- "
                  "was it generated by the current tools/gen_timetable.py?")
            return 2
    threshold = min(values.values())

    today = datetime.datetime.now(datetime.timezone.utc).date()
    days_left = (to_date(threshold) - today).days

    if days_left <= args.days:
        print(
            f"::error::The compiled timetable's earlier validity bound "
            f"({threshold}) is only {days_left} day(s) away (warning window "
            f"is {args.days} days). Check whether Caltrain has published a newer "
            "GTFS feed (feed_info.txt feed_end_date past the current one); if so, "
            "regenerate both headers: "
            "`python3 tools/gen_stations.py && python3 tools/gen_timetable.py`, "
            "then `cd test && make` to confirm, and commit the result. If the "
            "newest feed ends on the same date, there is nothing to regenerate yet."
        )
        return 1

    print(f"Timetable good for {days_left} more day(s) "
          f"(earlier bound {threshold}); {args.days}-day gate not yet due.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
